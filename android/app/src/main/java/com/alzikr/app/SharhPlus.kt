    fun of(id: String): Extra? = all[id]

    /** Plain text of the extra explanation, for copy/share. */
    fun text(e: Extra): String = buildString {
        append("تنبيه: ").append(e.note).append("\n\n")
        e.sections.forEach { (h, b) -> append(h).append('\n').append(b).append("\n\n") }
        append("المصادر:\n"); e.sources.forEach { append("• ").append(it).append('\n') }
    }

    /** The first words of the hadith, without marks or punctuation, as a search phrase. */
    fun phrase(title: String, text: String): String {
        val src = title.ifBlank { text }
        val clean = src.replace(Regex("[\\u064B-\\u065F\\u0670\\u06D6-\\u06ED]"), "")
            .replace(Regex("[^\\p{L}\\p{N}\\s]"), " ").trim()
        return clean.split(Regex("\\s+")).filter { it.isNotBlank() }.take(9).joinToString(" ")
    }

