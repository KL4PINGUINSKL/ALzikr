        "أيام التشريق: الحادي عشر والثاني عشر والثالث عشر من ذي الحجة.",
    )

    fun today(): List<Fact> = DailyBag.pick("learn", facts.map { it.id }, 3).mapNotNull { id -> facts.firstOrNull { it.id == id } }
    const val BOND = 5
    private val sp get() = Store.prefs
    fun learned() = sp.getString("learn_done", "") == LocalDate.now().toString()
    fun learn() {
        if (learned()) return
        sp.edit().putString("learn_done", LocalDate.now().toString()).putInt("learn_count", sp.getInt("learn_count", 0) + 1).apply()
        Progress.bond("learn", BOND)
        Pet.cheer("ما شاء الله! تعلّمت اليوم شيئًا جديدًا 📚", key = "learn", xp = false)
        Store.bump()
    }
    fun undo() {
        if (!learned()) return
        sp.edit().remove("learn_done").putInt("learn_count", (sp.getInt("learn_count", 0) - 1).coerceAtLeast(0)).apply()
        Progress.unbond("learn"); Store.bump()
    }
}

/** «تعلّم اليوم»: three facts and one «تعلّمتها» for the whole section (shown after a short read). */
@Composable
fun LearnSection() {
    @Suppress("UNUSED_VARIABLE") val v = Store.version
    val list = Learn.today()
    if (list.isEmpty()) return
    Text("تعلّم اليوم · +${Quran.digits(Learn.BOND)} ❤ للقسم كله", color = P.ink, fontSize = 14.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(top = 12.dp))
    Column(Modifier.fillMaxWidth().padding(top = 4.dp).clip(L.shape(12.dp)).background(P.card).padding(10.dp)) {
        list.forEach { fct ->
            Row(Modifier.fillMaxWidth().padding(vertical = 4.dp), verticalAlignment = Alignment.Top) {
                Text("📚", fontSize = 15.sp, modifier = Modifier.padding(end = 6.dp))
                Column(Modifier.weight(1f)) {
                    Text(fct.cat, color = P.gold, fontSize = 11.sp, fontWeight = FontWeight.SemiBold)
                    Text(fct.text, color = P.ink, fontSize = 14.sp, lineHeight = 22.sp)
                }
            }
        }
        if (Learn.learned()) {
            Row(Modifier.fillMaxWidth().padding(top = 6.dp), verticalAlignment = Alignment.CenterVertically) {
                Text("✓ تعلّمتها اليوم" + (Progress.bondGot("learn")?.let { " · +${Quran.digits(it)} ❤" } ?: ""), color = P.accent, fontSize = 13.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.weight(1f))
                Action("إلغاء", filled = false) { Learn.undo() }
            }
        } else {
            // A short read first: the button comes after a few seconds with the facts.
            var ready by remember { mutableStateOf(false) }
            LaunchedEffect(Unit) { kotlinx.coroutines.delay(8_000); ready = true }
            if (ready) Action("📚 قرأتها وتعلّمتها", Modifier.fillMaxWidth().padding(top = 8.dp)) { Learn.learn() }
            else Sub("اقرأها بتمهّل… يظهر زر «تعلّمتها» بعد لحظات.", Modifier.padding(top = 6.dp), size = 11.sp)
        }
    }
}
