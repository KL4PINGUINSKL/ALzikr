    fun byId(id: String) = topics.firstOrNull { it.id == id }

    data class Hit(val topic: Topic, val sec: Sec, val item: Item)
    fun search(q: String): List<Hit> {
        val words = Quran.normalize(q).split(' ').filter { it.length >= 2 }
        if (words.isEmpty()) return emptyList()
        return topics.flatMap { t -> t.secs.flatMap { s -> s.items.map { Hit(t, s, it) } } }
            .filter { h -> val n = Quran.normalize(h.sec.title + " " + h.item.text); words.all { n.contains(it) } }.take(60)
    }
}

/** All the fiqh cards with a search over them. [open] opens a page by id ("fiqh:<id>", "salah", "zakat"…). */
@Composable
fun FiqhHome(open: (String) -> Unit) {
    var q by rememberSaveable { mutableStateOf("") }
    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(16.dp), verticalArrangement = Arrangement.spacedBy(10.dp)) {
        OutlinedTextField(q, { q = it }, singleLine = true, modifier = Modifier.fillMaxWidth(), placeholder = { Text("ابحث في الأحكام: نواقض الوضوء، المسح، الكفارة…") })
        if (q.isNotBlank()) {
            val hits = Fiqh.search(q)
            if (hits.isEmpty()) Sub("لا نتائج. جرّب كلمة أخرى.")
            hits.forEach { h ->
                Column(Modifier.fillMaxWidth().clip(L.shape(14.dp)).background(P.surface).clickable { open("fiqh:${h.topic.id}") }.padding(12.dp)) {
                    Sub("${h.topic.title} › ${h.sec.title}", color = P.gold, size = 12.sp)
                    Text(h.item.text, color = P.ink, fontSize = 15.sp, lineHeight = 24.sp)
                }
            }
            return@Column
        }
        Sub("ملخّصات ميسّرة على قول جمهور العلماء مع الدليل، ويُنبَّه على الخلاف المشهور. للمسائل الخاصة اسأل أهل العلم.", size = 12.sp)
        Fiqh.topics.forEach { t ->
            Row(Modifier.fillMaxWidth().clip(L.shape(16.dp)).background(P.surface).clickable { open("fiqh:${t.id}") }.padding(14.dp), verticalAlignment = Alignment.CenterVertically) {
                Glyph(t.icon, tint = P.accent, size = 28.dp)
                Column(Modifier.weight(1f).padding(horizontal = 12.dp)) {
                    Text(t.title, color = P.ink, fontSize = 17.sp, fontWeight = FontWeight.SemiBold)
                    Sub(t.secs.joinToString(" · ") { it.title }, size = 12.sp)
                }
                Text("›", color = P.muted, fontSize = 20.sp)
            }
        }
        Row(Modifier.fillMaxWidth().clip(L.shape(16.dp)).background(P.surface).clickable { open("salah") }.padding(14.dp), verticalAlignment = Alignment.CenterVertically) {
            Glyph("💧", tint = P.accent, size = 28.dp)
            Column(Modifier.weight(1f).padding(horizontal = 12.dp)) {
                Text("صفة الوضوء والصلاة", color = P.ink, fontSize = 17.sp, fontWeight = FontWeight.SemiBold)
                Sub("الوضوء والصلاة خطوة خطوة، وسجود السهو، وصلاة المسافر والمريض", size = 12.sp)
            }
            Text("›", color = P.muted, fontSize = 20.sp)
        }
    }
}

@Composable
fun FiqhPage(id: String, open: (String) -> Unit) {
    val t = Fiqh.byId(id) ?: return
    var openSec by rememberSaveable(id) { mutableStateOf(0) }
    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(16.dp), verticalArrangement = Arrangement.spacedBy(10.dp)) {
        Panel(color = P.accent.copy(alpha = .10f)) { Text(t.intro, color = P.ink, fontSize = (15 * Data.textScale).sp, lineHeight = (25 * Data.textScale).sp) }
        t.secs.forEachIndexed { k, s ->
            val isOpen = openSec == k
            Column(Modifier.fillMaxWidth().clip(L.shape(14.dp)).background(P.surface).border(1.dp, if (isOpen) P.accent.copy(alpha = .5f) else P.line, L.shape(14.dp))) {
                Row(Modifier.fillMaxWidth().clickable { openSec = if (isOpen) -1 else k }.padding(14.dp), verticalAlignment = Alignment.CenterVertically) {
                    Text(s.title, color = P.ink, fontSize = 16.sp, fontWeight = FontWeight.Bold, modifier = Modifier.weight(1f))
                    Sub("${Quran.digits(s.items.size)}  ${if (isOpen) "▴" else "▾"}")
                }
                if (isOpen) Column(Modifier.padding(start = 14.dp, end = 14.dp, bottom = 14.dp), verticalArrangement = Arrangement.spacedBy(10.dp)) {
                    s.items.forEach { it ->
                        Row {
                            Text("•", color = P.accent, fontSize = 18.sp, modifier = Modifier.padding(end = 8.dp))
                            Column(Modifier.weight(1f)) {
                                Text(it.text, color = P.ink, fontSize = (15 * Data.textScale).sp, lineHeight = (25 * Data.textScale).sp)
                                if (it.src.isNotBlank()) Sub(it.src, Modifier.padding(top = 2.dp), size = 11.sp, color = P.gold)
                            }
                        }
                    }
                }
            }
        }
        if (t.links.isNotEmpty()) Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            t.links.forEach { (label, to) -> Choice(label, false) { open(to) } }
        }
        Sub("ملخّص ميسّر على قول جمهور العلماء. للمسائل الخاصة اسأل أهل العلم.", Modifier.padding(4.dp), size = 11.sp)
    }
}
