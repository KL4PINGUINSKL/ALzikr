/** One proof, tappable: a verse opens in the mushaf, a hadith or athar opens its own page. */
@Composable
private fun EvidenceRow(e: Fiqh.Ev, open: (Fiqh.Ev) -> Unit) {
    val (icon, label) = when (e.kind) {
        Fiqh.Kind.QURAN -> "📖" to "آية: ${Quran.surahs.getOrNull(e.s - 1)?.name ?: ""} ${Quran.digits(e.a)}"
        Fiqh.Kind.HADITH -> "📜" to "حديث"
        Fiqh.Kind.ATHAR -> "🗒" to "أثر"
        Fiqh.Kind.IJMA -> "🤝" to "إجماع"
    }
    val tappable = e.kind != Fiqh.Kind.IJMA
    Column(Modifier.fillMaxWidth().clip(L.shape(12.dp)).background(P.accent.copy(alpha = .07f)).border(1.dp, P.accent.copy(alpha = .25f), L.shape(12.dp))
        .then(if (tappable) Modifier.clickable { open(e) } else Modifier).padding(horizontal = 10.dp, vertical = 8.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            GText("$icon $label", color = P.accent, fontSize = 12.sp, fontWeight = FontWeight.Bold)
            if (e.by.isNotBlank()) Text(" · ${e.by}", color = P.muted, fontSize = 11.sp, maxLines = 1, overflow = TextOverflow.Ellipsis, modifier = Modifier.weight(1f))
            else androidx.compose.foundation.layout.Spacer(Modifier.weight(1f))
            if (tappable) Text("‹", color = P.accent, fontSize = 16.sp)
        }
        Text("«${e.text}»", color = P.ink, fontSize = (15 * Data.textScale).sp, lineHeight = (25 * Data.textScale).sp, fontFamily = Fonts.naskh, maxLines = 3, overflow = TextOverflow.Ellipsis)
        if (e.src.isNotBlank()) Text(e.src, color = P.gold, fontSize = 11.sp)
    }
}

/** A hadith or athar given as evidence: its text, narrator and source, then its full text, grade, explanation and benefits. */
@Composable
fun FiqhEvidencePage(e: Fiqh.Ev, back: () -> Unit) {
    val ctx = LocalContext.current
    androidx.activity.compose.BackHandler(onBack = back)
    var openSharh by rememberSaveable { mutableStateOf<String?>(null) }
    var openBook by rememberSaveable { mutableStateOf<Pair<String, String>?>(null) }
    var searchAll by rememberSaveable { mutableStateOf(false) }
    openSharh?.let { SharhOpen(it) { openSharh = null }; return }
    openBook?.let { (b, n) -> HadithReader(b, 0, { openBook = null }, focus = n); return }
    val key = remember(e) { Fiqh.keyOf(e) }
    if (searchAll) { HadithSearchPage(initial = key) { searchAll = false }; return }
    var sharh by remember(e) { mutableStateOf<List<HadithSearch.Hit>?>(null) }
    var books by remember(e) { mutableStateOf<List<HadithSearch.Hit>?>(null) }
    LaunchedEffect(e) {
        withContext(Dispatchers.IO) {
            // The most words that still find it: fewer words when the exact wording differs.
            val words = key.split(' ').filter { it.isNotBlank() }
            var s = emptyList<HadithSearch.Hit>()
            for (n in words.size downTo minOf(2, words.size)) { s = runCatching { HadithSearch.searchSharh(ctx, words.take(n).joinToString(" "), 8) }.getOrDefault(emptyList()); if (s.isNotEmpty()) break }
            sharh = s
            var b = emptyList<HadithSearch.Hit>()
            for (n in words.size downTo minOf(2, words.size)) { b = runCatching { HadithSearch.searchBooks(ctx, words.take(n).joinToString(" "), 12) }.getOrDefault(emptyList()); if (b.isNotEmpty()) break }
            books = b
        }
    }
    Subpage(if (e.kind == Fiqh.Kind.ATHAR) "الأثر" else "الحديث", back) {
        Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(16.dp), verticalArrangement = Arrangement.spacedBy(10.dp)) {
            Panel(color = P.card) {
                Text("«${e.text}»", color = P.ink, fontSize = (19 * Data.textScale).sp, lineHeight = (33 * Data.textScale).sp, fontFamily = Fonts.naskh)
                if (e.by.isNotBlank()) Row(Modifier.padding(top = 8.dp)) { Sub("الراوي: ", color = P.gold); Text(e.by, color = P.ink, fontSize = 14.sp, modifier = Modifier.weight(1f)) }
                if (e.src.isNotBlank()) Row(Modifier.padding(top = 4.dp)) { Sub("المصدر والدرجة: ", color = P.gold); Text(e.src, color = P.ink, fontSize = 14.sp, modifier = Modifier.weight(1f)) }
            }
            Title("💡 الشرح والفوائد والدرجة")
            when (val s = sharh) {
                null -> Box(Modifier.fillMaxWidth().padding(12.dp), contentAlignment = Alignment.Center) { CircularProgressIndicator(color = P.accent) }
                else -> if (s.isEmpty()) Sub("لم أجده في موسوعة الأحاديث المشروحة (تحتاج الإنترنت أول مرة). جرّب البحث الكامل في الأسفل.")
                else s.forEachIndexed { k, hit ->
                    Column(Modifier.fillMaxWidth().clip(L.shape(14.dp)).background(if (k == 0) P.accent.copy(alpha = .12f) else P.surface).clickable { hit.sharhId?.let { openSharh = it } }.padding(12.dp)) {
                        Text(hit.text, color = P.ink, fontSize = 15.sp, fontFamily = Fonts.naskh, lineHeight = 25.sp, maxLines = 4, overflow = TextOverflow.Ellipsis)
                        Sub(if (k == 0) "افتح: نص الحديث والدرجة والشرح والفوائد ومعاني الكلمات ›" else "افتح الشرح ›", size = 12.sp, color = P.accent)
                    }
                }
            }
            Title("📚 في كتب الحديث على هاتفك")
            when (val b = books) {
                null -> Box(Modifier.fillMaxWidth().padding(12.dp), contentAlignment = Alignment.Center) { CircularProgressIndicator(color = P.accent) }
                else -> if (b.isEmpty()) Sub("لم أجده في الكتب المنزّلة. نزّل صحيح البخاري ومسلم وغيرهما من «المكتبة › الحديث» ليظهر هنا برقمه.")
                else b.forEach { hit ->
                    Column(Modifier.fillMaxWidth().clip(L.shape(14.dp)).background(P.surface).border(1.dp, P.line, L.shape(14.dp)).clickable { openBook = hit.book to hit.number }.padding(12.dp)) {
                        Text(hit.text, color = P.ink, fontSize = 15.sp, fontFamily = Fonts.naskh, lineHeight = 25.sp, maxLines = 5, overflow = TextOverflow.Ellipsis)
                        Text("${hit.bookTitle} · رقم ${hit.number}", color = P.gold, fontSize = 12.sp, fontWeight = FontWeight.SemiBold)
                    }
                }
            }
            Action("🔍 بحث كامل عن هذا الحديث", Modifier.fillMaxWidth(), filled = false) { searchAll = true }
        }
    }
}

