            )),
        )),
    )

    fun byId(id: String) = topics.firstOrNull { it.id == id }

    data class Hit(val topic: Topic, val sec: Sec, val item: Item)
    fun search(q: String): List<Hit> {
        val words = Quran.normalize(q).split(' ').filter { it.length >= 2 }
        if (words.isEmpty()) return emptyList()
        return topics.flatMap { t -> t.secs.flatMap { s -> s.items.map { Hit(t, s, it) } } }.filter { h ->
            val n = Quran.normalize(h.sec.title + " " + h.item.text + " " + h.item.ev.joinToString(" ") { it.text } + " " + (h.item.mz?.let { "${it.hanafi} ${it.maliki} ${it.shafii} ${it.hanbali}" } ?: ""))
            words.all { n.contains(it) }
        }.take(60)
    }

    /** Words to find a hadith by: the given key, else the first distinctive words of its text. */
    fun keyOf(e: Ev): String {
        if (e.key.isNotBlank()) return e.key
        val stop = setOf("قال", "رسول", "الله", "صلى", "عليه", "وسلم", "عن", "في", "من", "ان", "ما", "لا", "اذا", "ثم", "او", "على")
        return Quran.normalize(e.text).replace(Regex("[^ء-ي\\s]"), " ").split(' ').filter { it.length >= 2 && it !in stop }.take(4).joinToString(" ")
    }
}

